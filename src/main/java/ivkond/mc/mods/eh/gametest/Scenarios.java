package ivkond.mc.mods.eh.gametest;

import net.minecraft.gametest.framework.GameTestHelper;

import java.util.List;
import java.util.function.Consumer;

/**
 * Central catalogue of every game test scenario. Used by the 26.1+ NeoForge
 * bootstrap to register {@code Consumer<GameTestHelper>} test functions into
 * the {@code test_function} registry; older versions discover the same methods
 * through {@code @GameTest} annotations.
 */
public final class Scenarios {
    /**
     * @param name     test id under the {@code easy_homes} namespace
     * @param test     scenario body
     * @param maxTicks timeout in ticks; cooldown tests need room for real-time waits
     */
    public record Entry(String name, Consumer<GameTestHelper> test, int maxTicks) {
    }

    public static final List<Entry> ALL = List.of(
            new Entry("sethome_default", h -> new SetHomeScenarios().setDefaultHome(h), 100),
            new Entry("sethome_named", h -> new SetHomeScenarios().setNamedHome(h), 100),
            new Entry("sethome_overwrite", h -> new SetHomeScenarios().overwriteHome(h), 100),
            new Entry("sethome_invalid_names", h -> new SetHomeScenarios().invalidNames(h), 100),
            new Entry("sethome_auto_name", h -> new SetHomeScenarios().autoGeneratedName(h), 100),
            new Entry("sethome_max_homes", h -> new SetHomeScenarios().maxHomesLimit(h), 100),
            new Entry("sethome_creative_limit", h -> new SetHomeScenarios().creativeIgnoresLimit(h), 100),
            new Entry("sethome_persistence", h -> new SetHomeScenarios().persistenceRoundtrip(h), 100),
            new Entry("home_teleport", h -> new HomeScenarios().teleportToNamedHome(h), 100),
            new Entry("home_default", h -> new HomeScenarios().teleportToDefaultHome(h), 100),
            new Entry("home_unknown", h -> new HomeScenarios().unknownHome(h), 100),
            new Entry("home_invalid_name", h -> new HomeScenarios().invalidHomeName(h), 100),
            new Entry("home_cooldown", h -> new HomeScenarios().cooldownBlocksThenExpires(h), 200),
            new Entry("home_creative_cooldown", h -> new HomeScenarios().creativeIgnoresCooldown(h), 100),
            new Entry("home_cross_dimension", h -> new HomeScenarios().crossDimensionalHome(h), 100),
            new Entry("home_unknown_dimension", h -> new HomeScenarios().unknownDimensionHome(h), 100),
            new Entry("home_out_of_bounds", h -> new HomeScenarios().outOfBoundsPosition(h), 100),
            new Entry("home_mounted", h -> new HomeScenarios().mountedPlayerRejected(h), 100),
            new Entry("delhome_existing", h -> new DelHomeScenarios().deleteExistingHome(h), 100),
            new Entry("delhome_unknown", h -> new DelHomeScenarios().deleteUnknownHome(h), 100),
            new Entry("delhome_invalid_name", h -> new DelHomeScenarios().deleteInvalidName(h), 100),
            new Entry("renhome_rename", h -> new RenHomeScenarios().renameHome(h), 100),
            new Entry("renhome_unknown", h -> new RenHomeScenarios().renameUnknownHome(h), 100),
            new Entry("renhome_invalid_new_name", h -> new RenHomeScenarios().renameToInvalidName(h), 100),
            new Entry("renhome_over_existing", h -> new RenHomeScenarios().renameOverExistingHome(h), 100),
            new Entry("back_no_history", h -> new BackScenarios().backWithoutHistory(h), 100),
            new Entry("back_previous_home", h -> new BackScenarios().backReturnsToPreviousHome(h), 100),
            new Entry("back_alternates", h -> new BackScenarios().backAlternates(h), 100),
            new Entry("back_ignores_repeat", h -> new BackScenarios().backIgnoresRepeatedHome(h), 100),
            new Entry("homes_list", h -> new HomesScenarios().listHomes(h), 100),
            new Entry("homes_list_empty", h -> new HomesScenarios().listEmptyHomes(h), 100)
    );

    private Scenarios() {
    }
}
